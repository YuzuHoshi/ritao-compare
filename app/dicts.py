_ALIAS_GROUPS: dict[str, set[str]] | None = None


def _alias_groups() -> dict[str, set[str]]:
    global _ALIAS_GROUPS
    if _ALIAS_GROUPS is not None:
        return _ALIAS_GROUPS
    parent: dict[str, str] = {}

    def find(x: str) -> str:
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(a: str, b: str) -> None:
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[rb] = ra

    for cn, jp in (list(SERIES_MAP) + list(CHARACTER_MAP) + list(_EXTRA_ALIASES)
                   + list(CATEGORY_MAP) + list(CATEGORY_MAP_V2)):
        cn, jp = (cn or "").strip(), (jp or "").strip()
        if cn and jp:
            union(cn, jp)
    groups: dict[str, set[str]] = {}
    for term in list(parent):
        groups.setdefault(find(term), set()).add(term)
    _ALIAS_GROUPS = {t: g for g in groups.values() for t in g}
    return _ALIAS_GROUPS


def aliases_for(term: str) -> list[str]:
    """All known CN/JP spellings of a series or character, including itself."""
    t = (term or "").strip()
    if not t:
        return []
    grp = _alias_groups().get(t)
    if not grp:
        return [t]
    out = [x for x in grp if len(x) >= 2]
    return sorted(out, key=len, reverse=True) or [t]
